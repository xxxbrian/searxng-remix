const dictionaries: Record<UiLocale, Dictionary> = { en, 'zh-CN': zhCN, 'zh-TW': zhTW, ja, de, fr, es }

export function translate(locale: string, key: UiTextKey, values: Record<string, string | number> = {}): string {
  const dictionary = dictionaries[resolveUiLocale(locale)] ?? en
  return dictionary[key].replace(/\{(\w+)\}/g, (placeholder, name: string) => String(values[name] ?? placeholder))
}

export interface I18nContextValue {
  readonly locale: UiLocale
  readonly languages: readonly LanguageOption[]
  readonly aiEnabled: boolean
  readonly aiAuto: boolean
  t: (key: UiTextKey, values?: Record<string, string | number>) => string
}

// Root failures can render before public context loads. Their UI has an explicit English fallback.
const fallback: I18nContextValue = {
  locale: 'en',
  languages: [],
  aiEnabled: false,
  aiAuto: false,
  t: (key, values) => translate('en', key, values),
}
const I18nContext = createContext<I18nContextValue>(fallback)

export function I18nProvider(props: { publicContext: PublicContext | undefined; children: JSX.Element }) {
  const value: I18nContextValue = {
    get locale() {
      return resolveUiLocale(props.publicContext?.locale ?? 'en')
    },
    get languages() {
      return props.publicContext?.languages ?? []
    },
    get aiEnabled() {
      return props.publicContext?.aiEnabled ?? false
    },
    get aiAuto() {
      return props.publicContext?.aiAuto ?? false
    },
    t: (key, values) => translate(props.publicContext?.locale ?? 'en', key, values),
  }
  return <I18nContext.Provider value={value}>{props.children}</I18nContext.Provider>
}

export function useI18n(): I18nContextValue {
  return useContext(I18nContext)
}
