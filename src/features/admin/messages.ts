export const adminDictionaries: Record<UiLocale, Dictionary> = { en, 'zh-CN': zhCN, 'zh-TW': zhTW, ja, de, fr, es }

const fill = (text: string, values: Record<string, string | number>) =>
  text.replace(/\{(\w+)\}/g, (placeholder, name: string) => String(values[name] ?? placeholder))

export function adminText(locale: UiLocale, key: AdminTextKey, values: Record<string, string | number> = {}): string {
  return fill(adminDictionaries[locale][key], values)
}
